package dev.sharpy.localaze.generator

/**
 * Turns a [GenerationPlan] into Kotlin source.
 *
 * Every decision was made by the plan. This file only spells it, which is why
 * it has no failure path: a plan that reached here compiles.
 */

/** Words Kotlin will not accept as an identifier without backticks. */
private val reserved = setOf(
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if",
    "in", "interface", "is", "null", "object", "package", "return", "super", "this",
    "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while",
)

private val types = mapOf(
    "STRING" to "String",
    "NUMBER" to "Number",
    "DATETIME" to "Instant",
)

/**
 * The JVM caps one string constant at 65,535 bytes of modified UTF-8, and a
 * catalog of a few thousand keys passes that. Ten thousand UTF-16 units is at
 * most 30,000 bytes, so a chunk this size always compiles.
 */
private const val CHUNK = 10_000

/**
 * The JVM also caps one method at 64 KB of bytecode, and a map literal of a few
 * thousand signature entries is one method. Five hundred entries per function
 * stays well clear.
 */
private const val SIGNATURE_CHUNK = 500

private fun escape(identifier: String): String =
    if (identifier in reserved) "`$identifier`" else identifier

/** The Kotlin source for [plan], in package [packageName]. */
fun emitKotlin(plan: GenerationPlan, packageName: String): String {
    val out = StringBuilder()
    header(out, plan, packageName)
    type(out, plan)
    signature(out, plan)
    plurals(out, plan)
    compiledIn(out, plan)
    return out.toString()
}

private fun StringBuilder.line(text: String = "") {
    append(text).append('\n')
}

private fun header(out: StringBuilder, plan: GenerationPlan, packageName: String) = with(out) {
    line("// GENERATED BY LOCALAZE — DO NOT EDIT.")
    line("// Regenerate with `java -jar localaze-generator.jar`. Hand edits are lost.")
    line("//")
    line("// environment: ${comment(plan.environment)}")
    line("// version:     ${comment(plan.version)}")
    line("// hash:        ${comment(plan.contentHash)}")
    line("// source:      ${comment(plan.sourceLanguage)}")
    line()
    line("@file:Suppress(\"unused\", \"UNUSED_PARAMETER\", \"ObjectPropertyName\", \"FunctionName\", \"RemoveRedundantQualifierName\")")
    line()
    line("package $packageName")
    line()
    line("import dev.sharpy.localaze.LocalazeConfig")
    line("import dev.sharpy.localaze.LocalazeRuntime")
    line("import dev.sharpy.localaze.LocalazeSignature")
    line("import java.time.Instant")
    line()
}

private fun type(out: StringBuilder, plan: GenerationPlan) = with(out) {
    val locales = plan.languages.joinToString(", ") { literal(it) }
    line("/**")
    line(" * Typed translations, generated from release ${kdoc(plan.version)}.")
    line(" *")
    line(" * Every accessor is typed: a message that selects on a count cannot be")
    line(" * called without one, and the compiler checks it.")
    line(" */")
    line("class Localaze private constructor(")
    line("    /** The runtime behind these accessors, for the update machinery. */")
    line("    val runtime: LocalazeRuntime,")
    line(") {")

    for ((index, key) in plan.keys.withIndex()) {
        if (index > 0) line()
        accessor(out, key)
    }

    if (plan.keys.isNotEmpty()) line()
    line("    companion object {")
    line("        /** The languages this release carries, source first. */")
    line("        val supportedLocales: List<String> = listOf($locales)")
    line()
    line("        const val SOURCE_LOCALE: String = ${literal(plan.sourceLanguage)}")
    line()
    line("        /**")
    line("         * The release this code was generated from. The update policy")
    line("         * compares every fetched catalog against it.")
    line("         */")
    line("        const val GENERATED_FROM: String = ${literal(plan.version)}")
    line()
    line("        const val CONTENT_HASH: String = ${literal(plan.contentHash)}")
    line()
    line("        /**")
    line("         * Translations for [locale]. A locale this release does not carry")
    line("         * starts from the source language's compiled-in catalog.")
    line("         */")
    line("        fun forLocale(locale: String, config: LocalazeConfig): Localaze =")
    line("            Localaze(")
    line("                LocalazeRuntime(")
    line("                    locale = locale,")
    line("                    config = config,")
    line("                    signature = _signature,")
    line("                    compiledIn = _compiledIn[locale] ?: _compiledIn.getValue(SOURCE_LOCALE),")
    line("                    pluralResolver = { _plural(locale, it) }))")
    line("    }")
    line("}")
    line()
}

private fun accessor(out: StringBuilder, key: PlannedKey) = with(out) {
    val docs = mutableListOf<String>()
    if (key.preview.isNotEmpty()) docs.add("`${kdoc(key.preview).replace('`', '\'')}`")
    key.selector?.let {
        if (docs.isNotEmpty()) docs.add("")
        docs.add("Selects on `$it`, so it cannot be called without it.")
    }
    when (docs.size) {
        0 -> Unit
        1 -> line("    /** ${docs[0]} */")
        else -> {
            line("    /**")
            docs.forEach { line(if (it.isEmpty()) "     *" else "     * $it") }
            line("     */")
        }
    }

    val name = escape(key.accessor)
    if (key.params.isEmpty()) {
        line("    val $name: String get() = this.runtime.render(${literal(key.key)})")
        return@with
    }

    val params = key.params.joinToString(", ") { "${escape(it.identifier)}: ${types.getValue(it.type)}" }
    val args = key.params.joinToString(", ") { "${literal(it.name)} to ${escape(it.identifier)}" }
    val selector = key.selector?.let { selected ->
        key.params.firstOrNull { it.name == selected }?.let { ", ${escape(it.identifier)}.toDouble()" }
    } ?: ""

    line("    fun $name($params): String =")
    line("        this.runtime.render(${literal(key.key)}, mapOf($args)$selector)")
}

// File-private helpers in the generated file start with an underscore. No
// accessor can, so a key named `plural` or `signature` cannot shadow them.

private fun signature(out: StringBuilder, plan: GenerationPlan) = with(out) {
    val chunks = plan.keys.chunked(SIGNATURE_CHUNK).ifEmpty { listOf(emptyList()) }
    line("// Signature — names and types. A fetched catalog is refused unless every key")
    line("// here is present and every parameter still matches.")
    line()
    line("private val _signature: LocalazeSignature = LocalazeSignature.of(")
    line("    " + chunks.indices.joinToString(" + ") { "_signature$it()" } + ")")
    for ((index, chunk) in chunks.withIndex()) {
        line()
        line("private fun _signature$index(): Map<String, List<Pair<String, String>>> = mapOf(")
        for (key in chunk) {
            val params = key.params.joinToString(", ") { "${literal(it.name)} to ${literal(it.type)}" }
            line("    ${literal(key.key)} to listOf<Pair<String, String>>($params),")
        }
        line(")")
    }
    line()
}

private fun plurals(out: StringBuilder, plan: GenerationPlan) = with(out) {
    line("// Plural rules — each language's CLDR rules, compiled by the server and")
    line("// published in the manifest. No CLDR data ships and no MF2 is parsed on device.")
    line()
    line("private fun _plural(locale: String, value: Double): String? = when (locale) {")
    for (plural in plan.plurals) {
        line("    ${literal(plural.language)} -> ${resolverName(plural.language)}(value)")
    }
    line("    else -> null")
    line("}")
    for (plural in plan.plurals) {
        line()
        resolver(out, plural)
    }
    line()
}

private fun resolver(out: StringBuilder, plural: PlannedPlural) = with(out) {
    val name = resolverName(plural.language)
    if (plural.categories.isEmpty()) {
        line("private fun $name(value: Double): String? = null")
        return@with
    }

    val usesV = plural.uses("v")
    val usesI = usesV || plural.uses("i")

    line("private fun $name(value: Double): String? {")
    line("    val n = Math.abs(value)")
    line("    if (n.isNaN() || n.isInfinite() || n >= 1e15) return null")
    if (usesI) line("    val i = Math.floor(n)")
    if (usesV) line("    val v = if (n == i) 0.0 else 1.0")
    line()
    for ((category, condition) in plural.categories) {
        line("    if (${kotlinCondition(condition)}) return ${literal(category)}")
    }
    line("    return null")
    line("}")
}

/**
 * Every integer literal becomes a `Double` literal. Kotlin will not compare a
 * `Double` with an `Int`, so `n`, `i` and `v` are all `Double` and so is every
 * number they meet.
 */
internal fun kotlinCondition(condition: String): String =
    Regex("(?<![\\w.])(\\d+)(?![\\w.])").replace(condition) { "${it.value}.0" }

private fun compiledIn(out: StringBuilder, plan: GenerationPlan) = with(out) {
    line("// Compiled-in catalogs — the floor. An app whose asset is missing or")
    line("// unreadable still renders text rather than key names.")
    line()
    line("private val _compiledIn: Map<String, String> = mapOf(")
    for (language in plan.languages) {
        val chunks = chunks(plan.catalogs.getValue(language))
        if (chunks.size == 1) {
            line("    ${literal(language)} to ${literal(chunks[0])},")
        } else {
            line("    ${literal(language)} to listOf(")
            chunks.forEach { line("        ${literal(it)},") }
            line("    ).joinToString(\"\"),")
        }
    }
    line(")")
}

/** [value] in pieces of at most [CHUNK] units, never splitting a surrogate pair. */
private fun chunks(value: String): List<String> {
    val out = mutableListOf<String>()
    var start = 0
    while (start < value.length) {
        var end = minOf(start + CHUNK, value.length)
        if (end < value.length && Character.isHighSurrogate(value[end - 1])) end -= 1
        out.add(value.substring(start, end))
        start = end
    }
    return out.ifEmpty { listOf("") }
}

/** `pt-BR` becomes `_pluralPtBr`. */
private fun resolverName(language: String): String =
    "_plural" + language.split('-', '_').joinToString("") { segment ->
        segment.take(1).uppercase() + segment.drop(1).lowercase()
    }

/** A Kotlin string literal holding exactly [value]. */
internal fun literal(value: String): String {
    val out = StringBuilder("\"")
    for (character in value) {
        when (character) {
            '\\' -> out.append("\\\\")
            '"' -> out.append("\\\"")
            '$' -> out.append("\\$")
            '\n' -> out.append("\\n")
            '\r' -> out.append("\\r")
            '\t' -> out.append("\\t")
            '\b' -> out.append("\\b")
            else ->
                if (character.code < 0x20 || character.code == 0x7F) {
                    out.append("\\u").append(String.format("%04x", character.code))
                } else {
                    out.append(character)
                }
        }
    }
    return out.append('"').toString()
}

/** Text safe inside a `//` comment: one line, nothing else. */
private fun comment(value: String): String = value.replace(Regex("[\\r\\n\\u2028\\u2029]+"), " ")

/** Text safe inside a KDoc block: one line, and never the end of the block. */
private fun kdoc(value: String): String = comment(value).replace("*/", "* /")
